def log(msg: str) -> None:
    sys.stderr.write(f"[coordn8:vendor] {msg}\n")
    sys.stderr.flush()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _entry(key: str, spec: dict, status: str, **extra) -> dict:
    e = {"lib": key, "status": status, "npm": spec.get("npm"),
         "version": spec.get("version"), "license": spec["license"],
         "spdx": spec.get("spdx"), "why": spec["why"], "url": spec["url"],
         "sha256_pinned": spec.get("sha256"),
         "integrity": "pinned" if spec.get("sha256") else "recorded-unpinned"}
    e.update(extra)
    return e


def load_manifest(vendor_dir: Path) -> dict:
    m = vendor_dir / "manifest.json"
    if not m.exists():
        return {}
    try:
        data = json.loads(m.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception:  # noqa: BLE001 — a broken manifest is rebuilt, never trusted
        return {}


def file_state(key: str, spec: dict, vendor_dir: Path, prev: dict | None) -> dict:
    """Is the vendored copy present AND current? Returns {ok, reason, sha256, bytes}.

    Current means: the bytes match the pinned sha256 (when pinned), or — for an
    unpinned file — the manifest says it was fetched at the pinned version."""
    out = vendor_dir / spec["file"]
    if not out.exists() or out.stat().st_size == 0:
        return {"ok": False, "reason": "not vendored yet"}
    data = out.read_bytes()
    digest = sha256_bytes(data)
    pin = spec.get("sha256")
    if pin:
        if digest == pin:
            return {"ok": True, "sha256": digest, "bytes": len(data)}
        return {"ok": False, "sha256": digest, "bytes": len(data),
                "reason": "vendored bytes do not match the pinned sha256 "
                          "(corrupt or a different version) — re-fetching"}
    prev_ver = (prev or {}).get("version")
    if prev_ver and prev_ver != spec.get("version"):
        return {"ok": False, "sha256": digest, "bytes": len(data),
                "reason": f"vendored version {prev_ver} != pinned {spec.get('version')} "
                          "— upgrading"}
    return {"ok": True, "sha256": digest, "bytes": len(data)}


def download(url: str, timeout: float) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "coordn8-vendor"})
    with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310 (https pinned)
        data = r.read(MAX_BYTES + 1)
    if not data:
        raise ValueError("empty response")
    if len(data) > MAX_BYTES:
        raise ValueError(f"response larger than {MAX_BYTES} bytes")
    return data


def fetch_one(key: str, spec: dict, vendor_dir: Path, prev: dict | None = None,
              timeout: float = 60) -> dict:
    out = vendor_dir / spec["file"]
    st = file_state(key, spec, vendor_dir, prev)
    if st["ok"]:
        return _entry(key, spec, "already-present", file=str(out), bytes=st["bytes"],
                      sha256=st["sha256"], verified=bool(spec.get("sha256")))
    try:
        data = download(spec["url"], timeout)
        digest = sha256_bytes(data)
        pin = spec.get("sha256")
        if pin and digest != pin:
            raise ValueError(f"sha256 mismatch: got {digest[:16]}…, pinned {pin[:16]}… "
                             "(download refused, nothing written)")
        vendor_dir.mkdir(parents=True, exist_ok=True)
        tmp = out.with_name(f".{out.name}.tmp-{os.getpid()}")
        tmp.write_bytes(data)
        os.replace(tmp, out)
        return _entry(key, spec, "fetched", file=str(out), bytes=len(data),
                      sha256=digest, verified=bool(pin),
                      replaced_reason=st.get("reason") if st.get("sha256") else None)
    except (urllib.error.URLError, ValueError, OSError) as e:
        return _entry(key, spec, "fetch-failed", file=None,
                      reason=f"{type(e).__name__}: {e}",
                      fix=f"needs network to cdn.jsdelivr.net; re-run "
                          f"python3 scripts/render/fetch_visual_libs.py --only {key}")


def merge_manifest(vendor_dir: Path, results: list[dict]) -> dict:
    """Merge this run's results into the existing manifest, keyed by lib."""
    old = load_manifest(vendor_dir)
    vend = {e.get("lib"): e for e in old.get("vendored", []) if isinstance(e, dict)}
    fail = {e.get("lib"): e for e in old.get("failed", []) if isinstance(e, dict)}
    for r in results:
        k = r["lib"]
        if r["status"] in ("fetched", "already-present"):
            vend[k] = r
            fail.pop(k, None)
        else:
            fail[k] = r
            # A fetch is only attempted when the vendored copy is missing or no
            # longer matches its pin/version, so the old entry is not current.
            vend.pop(k, None)
    return {"schema": 2,
            "vendored": [vend[k] for k in sorted(vend)],
            "failed": [fail[k] for k in sorted(fail)]}


def verify_dir(vendor_dir: Path, want: list[str]) -> dict:
    prev = {e.get("lib"): e for e in load_manifest(vendor_dir).get("vendored", [])}
    rows = []
    for k in want:
        st = file_state(k, LIBS[k], vendor_dir, prev.get(k))
        rows.append({"lib": k, "ok": st["ok"], "reason": st.get("reason"),
                     "sha256": st.get("sha256"), "pinned": LIBS[k].get("sha256")})
    return {"tool": "fetch_visual_libs", "verify": True, "vendor_dir": str(vendor_dir),
            "results": rows, "all_ok": all(r["ok"] for r in rows)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="_build/vendor",
                    help="where to vendor the JS files (default _build/vendor)")
    ap.add_argument("--only", nargs="*", default=None,
                    help=f"subset of {sorted(LIBS)}")
    ap.add_argument("--dry-run", action="store_true",
                    help="print the plan; download nothing")
    ap.add_argument("--verify", action="store_true",
                    help="no network: check vendored files against their pins")
    ap.add_argument("--timeout", type=float, default=60,
                    help="per-download timeout in seconds (default 60)")
    args = ap.parse_args(argv)

    want = list(args.only) if args.only else list(LIBS)
    unknown = [k for k in want if k not in LIBS]
    if unknown:
        log(f"unknown lib(s): {unknown}; known: {sorted(LIBS)}")
        return 2

    vendor_dir = Path(args.dir)

    if args.dry_run:
        plan = [{"lib": k, "url": LIBS[k]["url"], "file": LIBS[k]["file"],
                 "npm": LIBS[k]["npm"], "version": LIBS[k]["version"],
                 "sha256": LIBS[k]["sha256"], "spdx": LIBS[k]["spdx"],
                 "why": LIBS[k]["why"], "license": LIBS[k]["license"]}
                for k in want]
        print(json.dumps({"tool": "fetch_visual_libs", "dry_run": True,
                          "vendor_dir": str(vendor_dir), "plan": plan}, indent=2))
        log(f"would vendor {len(plan)} lib(s) into {vendor_dir} (nothing downloaded)")
        return 0

    if args.verify:
        rep = verify_dir(vendor_dir, want)
        print(json.dumps(rep, indent=2))
        return 0 if rep["all_ok"] else 1

    prev = {e.get("lib"): e for e in load_manifest(vendor_dir).get("vendored", [])}
    results = [fetch_one(k, LIBS[k], vendor_dir, prev.get(k), args.timeout) for k in want]
    ok = [r for r in results if r["status"] in ("fetched", "already-present")]
    failed = [r for r in results if r["status"] == "fetch-failed"]

    manifest = vendor_dir / "manifest.json"
    merged = None
    if ok or manifest.exists():
        merged = merge_manifest(vendor_dir, results)
        if merged["vendored"]:
            vendor_dir.mkdir(parents=True, exist_ok=True)
            tmp = manifest.with_name(f".manifest.json.tmp-{os.getpid()}")
            tmp.write_text(json.dumps(merged, indent=2), encoding="utf-8")
            os.replace(tmp, manifest)

    summary = {
        "tool": "fetch_visual_libs",
        "vendor_dir": str(vendor_dir),
        "vendored": ok,
        "failed": failed,
        "manifest": str(manifest) if (merged and merged["vendored"]) else None,
        "guidance": (
            "Inline the ones each scene uses into that scene's HTML (keeps the "
            "self-contained/offline contract). All are free & commercial-OK."
            if not failed else
            "Some libraries could not be downloaded (see 'failed' with the "
            "specific reason). Those visual techniques are limited until fetched; "
            "the rest are available. Never fake a vendored file."),
    }
    print(json.dumps(summary, indent=2))
    log(summary["guidance"])
    # Advisory: partial success is fine — the agent uses what vendored.
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
