#!/usr/bin/env python3
"""
Coordn8 — vendor the free client-side visual libraries LOCALLY.

The video and page get their craft from best-in-class, FREE, no-API JavaScript
libraries. To keep the self-contained/offline contract (the page is one file, a
scene renders with no network), we DOWNLOAD each library once into a local
`_build/vendor/` directory; the agent then INLINES the ones a scene uses directly
into that scene's HTML (and into the final page). After this one fetch, rendering
needs no network at all.

All libraries here are free for commercial use with no key/account/server:
  - GSAP (+ its now-free plugins)  — professional easing, timelines, morphing:
      the single biggest lever for "crafted, not linear-CSS" motion.
  - D3                             — force graphs, tree layouts, data transitions.
  - Rough.js                       — hand-drawn / sketchy aesthetic (warmth).
  - anime.js                       — lightweight keyframe/timeline motion.
  - dagre                          — layered graph layout (rank -> order ->
      coordinates): the deterministic layout engine every diagram is placed with.
      Its single-file build bundles its own graph library (same licence). It
      needs a host with `structuredClone` (every current browser; Node 17+).

We pin exact versions for reproducibility and fetch from jsDelivr (a public CDN
that serves the files of the published npm package). If a download fails (no
network), we say so specifically and which visual technique it limits — we never
fake a vendored file.

INTEGRITY. A file that is part of the published npm tarball is immutable for that
version, so its sha256 is PINNED below and checked on every fetch AND on every
re-run: a mismatching download is refused (nothing is written), and a vendored
file whose bytes no longer match its pin is treated as corrupt/outdated and
re-fetched. The pins were taken from a real download and cross-checked against
the CDN's own file-hash listing for the package version.
One file is NOT pinned: the Rough.js minified build is generated by the CDN (it is
not in the npm tarball), so its bytes can legitimately change; for it the sha256
is RECORDED in the manifest (provenance) but never enforced.

The manifest (`<dir>/manifest.json`) is MERGED, never overwritten wholesale:
fetching one library (`--only dagre`) keeps every other library's entry.

Usage:
  python3 scripts/render/fetch_visual_libs.py            # fetch all, into _build/vendor
  python3 scripts/render/fetch_visual_libs.py --dry-run  # print plan, fetch nothing
  python3 scripts/render/fetch_visual_libs.py --only gsap d3
  python3 scripts/render/fetch_visual_libs.py --dir path/to/vendor
  python3 scripts/render/fetch_visual_libs.py --verify   # offline: check vendored files against pins
"""
